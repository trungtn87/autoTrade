-- Private, interactive AI Analyst history. Additive only; trading and Dashboard untouched.
BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE IF NOT EXISTS autotrade_analytics.ai_chat_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    selected_event_id varchar(120) REFERENCES autotrade_analytics.ai_reviews(event_id),
    title varchar(120) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ai_chat_sessions_updated_idx
    ON autotrade_analytics.ai_chat_sessions(updated_at DESC);

CREATE TABLE IF NOT EXISTS autotrade_analytics.ai_chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id uuid NOT NULL REFERENCES autotrade_analytics.ai_chat_sessions(id),
    request_id uuid NOT NULL,
    role text NOT NULL CHECK (role IN ('user','assistant')),
    content text NOT NULL CHECK (length(content) BETWEEN 1 AND 12000),
    model text,
    error_code text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(request_id,role)
);
CREATE INDEX IF NOT EXISTS ai_chat_messages_session_idx
    ON autotrade_analytics.ai_chat_messages(session_id,created_at,id);
CREATE INDEX IF NOT EXISTS ai_chat_messages_daily_idx
    ON autotrade_analytics.ai_chat_messages(role,created_at DESC);

ALTER TABLE autotrade_analytics.ai_chat_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE autotrade_analytics.ai_chat_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE autotrade_analytics.ai_chat_sessions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE autotrade_analytics.ai_chat_messages FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE autotrade_analytics.ai_chat_messages_id_seq
    FROM PUBLIC, anon, authenticated;
COMMENT ON TABLE autotrade_analytics.ai_chat_sessions IS
    'Private owner-only AI Analyst conversations, never exposed on public Dashboard.';
COMMENT ON TABLE autotrade_analytics.ai_chat_messages IS
    'Private Gemini Q&A history; never used for trading decisions or to modify immutable AI reviews.';
COMMIT;
