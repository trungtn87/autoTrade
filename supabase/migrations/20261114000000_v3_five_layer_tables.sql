-- AutoTrade V3 (five layers, Issues #107/#108/#109): brand-new tables only.
-- Additive: no DROP/ALTER of any existing table. Old tables (public.candles,
-- public.system_events, public.discord_trade_outbox, public.processed_targets,
-- autotrade_analytics.*) are left untouched for reading; V3 never writes them.
-- Re-runnable: every statement is IF NOT EXISTS / ON CONFLICT DO NOTHING.
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE SCHEMA IF NOT EXISTS autotrade_v3;

-- 1. L1 candles (same columns as the V2 store so 20FINAL input is identical).
CREATE TABLE IF NOT EXISTS autotrade_v3.candles (
    symbol      text             NOT NULL,
    timeframe   text             NOT NULL,
    open_time   bigint           NOT NULL,
    open        double precision NOT NULL,
    high        double precision NOT NULL,
    low         double precision NOT NULL,
    close       double precision NOT NULL,
    volume      double precision NOT NULL,
    close_time  bigint           NOT NULL,
    created_at  timestamptz      NOT NULL DEFAULT now(),
    PRIMARY KEY (symbol, timeframe, open_time)
);

-- One-time read-only copy of already validated candles so V3 does not need a
-- 3400-bar REST bootstrap. The source table is only SELECTed.
DO $$
BEGIN
    IF to_regclass('public.candles') IS NOT NULL THEN
        INSERT INTO autotrade_v3.candles(symbol, timeframe, open_time, open, high, low, close, volume, close_time)
        SELECT symbol, timeframe, open_time, open, high, low, close, volume, close_time
        FROM public.candles
        ON CONFLICT (symbol, timeframe, open_time) DO NOTHING;
    END IF;
END $$;

-- 2. L2 strategy signals: exactly the 9 agreed fields.
CREATE TABLE IF NOT EXISTS autotrade_v3.strategy_signals (
    event_id     text        PRIMARY KEY,
    symbol       text        NOT NULL,
    combo        text        NOT NULL,
    side         text        NOT NULL CHECK (side IN ('BUY', 'SELL')),
    signal_time  timestamptz NOT NULL,
    entry        numeric     NOT NULL,
    tp           numeric     NOT NULL,
    sl           numeric     NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS strategy_signals_symbol_time_idx
    ON autotrade_v3.strategy_signals(symbol, signal_time DESC);

-- 3. L3 execution: one row per signal. client_order_id UNIQUE is the only
-- dedupe: the same event can never produce a second Entry POST.
CREATE TABLE IF NOT EXISTS autotrade_v3.execution_orders (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id                   text        NOT NULL UNIQUE,
    client_order_id            text        NOT NULL UNIQUE,
    symbol                     text        NOT NULL,
    combo                      text        NOT NULL,
    side                       text        NOT NULL,
    leverage                   integer,
    requested_qty              numeric,
    entry_order_id             text,
    entry_status               text,
    executed_qty               numeric,
    avg_price                  numeric,
    filled_at                  timestamptz,
    exit_mode                  text,
    sl_order_id                text,
    sl_price                   numeric,
    sl_qty                     numeric,
    sl_status                  text,
    tp_order_id                text,
    tp_price                   numeric,
    tp_qty                     numeric,
    tp_status                  text,
    trailing_order_id          text,
    trailing_activation_price  numeric,
    trailing_callback_rate     numeric,
    trailing_qty               numeric,
    trailing_status            text,
    protection_status          text,
    stage                      text        NOT NULL DEFAULT 'claimed',
    error                      text,
    raw_entry                  jsonb       NOT NULL DEFAULT '{}'::jsonb,
    raw_protection             jsonb       NOT NULL DEFAULT '{}'::jsonb,
    l4_evidence                jsonb       NOT NULL DEFAULT '[]'::jsonb,
    created_at                 timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS execution_orders_symbol_created_idx
    ON autotrade_v3.execution_orders(symbol, created_at DESC);
CREATE INDEX IF NOT EXISTS execution_orders_entry_order_idx
    ON autotrade_v3.execution_orders(entry_order_id);

-- 4. Real close results (partial or full) collected by L4 from BingX history.
CREATE TABLE IF NOT EXISTS autotrade_v3.execution_results (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_order_id  bigint      NOT NULL REFERENCES autotrade_v3.execution_orders(id),
    event_id            text        NOT NULL,
    close_order_id      text        NOT NULL UNIQUE,
    close_type          text,
    closed_qty          numeric,
    close_price         numeric,
    realized_pnl        numeric,
    fee                 numeric,
    closed_at           timestamptz,
    raw                 jsonb       NOT NULL DEFAULT '{}'::jsonb,
    recorded_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS execution_results_order_idx
    ON autotrade_v3.execution_results(execution_order_id);

-- 5. Money per execution order (no account-wide finance table).
CREATE TABLE IF NOT EXISTS autotrade_v3.execution_finances (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_order_id  bigint      NOT NULL UNIQUE REFERENCES autotrade_v3.execution_orders(id),
    event_id            text        NOT NULL,
    margin              numeric,
    leverage            numeric,
    position_value      numeric,
    open_fee            numeric,
    close_fee           numeric,
    funding             numeric,
    gross_pnl           numeric,
    net_pnl             numeric,
    roi_pct             numeric,
    closed_qty          numeric,
    is_fully_closed     boolean     NOT NULL DEFAULT false,
    raw                 jsonb       NOT NULL DEFAULT '{}'::jsonb,
    updated_at          timestamptz NOT NULL DEFAULT now()
);

-- 6. Central problem log for all layers. One row per occurrence; no dedupe.
CREATE TABLE IF NOT EXISTS autotrade_v3.control_logs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      timestamptz NOT NULL DEFAULT now(),
    layer           text        NOT NULL CHECK (layer IN ('L1', 'L2', 'L3', 'L4', 'L5')),
    symbol          text,
    event_id        text,
    order_id        text,
    step            text,
    error_code      text,
    message         text        NOT NULL,
    details         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    discord_status  text        NOT NULL DEFAULT 'pending'
        CHECK (discord_status IN ('pending', 'sent', 'failed', 'disabled'))
);
CREATE INDEX IF NOT EXISTS control_logs_created_idx ON autotrade_v3.control_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS control_logs_event_idx ON autotrade_v3.control_logs(event_id);

-- The V3 schema is not exposed through the Supabase Data API. RLS without
-- policies keeps anon/authenticated out; the table owner (service) bypasses it.
ALTER TABLE autotrade_v3.candles            ENABLE ROW LEVEL SECURITY;
ALTER TABLE autotrade_v3.strategy_signals   ENABLE ROW LEVEL SECURITY;
ALTER TABLE autotrade_v3.execution_orders   ENABLE ROW LEVEL SECURITY;
ALTER TABLE autotrade_v3.execution_results  ENABLE ROW LEVEL SECURITY;
ALTER TABLE autotrade_v3.execution_finances ENABLE ROW LEVEL SECURITY;
ALTER TABLE autotrade_v3.control_logs       ENABLE ROW LEVEL SECURITY;

COMMIT;
