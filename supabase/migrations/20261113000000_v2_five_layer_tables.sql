-- AutoTrade V2 five-layer refactor (#107/#109): additive tables only.
-- No DROP here. Legacy tables are removed in a later, separately approved migration
-- after data has been verified and copied. Not applied to production by this PR.
BEGIN;
SET LOCAL lock_timeout='5s';

CREATE TABLE IF NOT EXISTS autotrade_analytics.strategy_signals (
    event_id     varchar(120) PRIMARY KEY,
    symbol       varchar(20)  NOT NULL CHECK (symbol IN ('BTC-USDT','ETH-USDT')),
    combo        varchar(40)  NOT NULL,
    side         varchar(10)  NOT NULL CHECK (side IN ('BUY','SELL')),
    signal_time  timestamptz  NOT NULL,
    entry        numeric      NOT NULL,
    tp           numeric      NOT NULL,
    sl           numeric      NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS strategy_signals_symbol_time_idx
    ON autotrade_analytics.strategy_signals(symbol, signal_time DESC);

CREATE TABLE IF NOT EXISTS autotrade_analytics.execution_orders (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          varchar(120) NOT NULL REFERENCES autotrade_analytics.strategy_signals(event_id),
    client_order_id   varchar(64)  NOT NULL UNIQUE,
    bingx_order_id    varchar(64),
    step              varchar(32)  NOT NULL,
    status            varchar(32)  NOT NULL,
    executed_qty      numeric,
    avg_price         numeric,
    raw_response      jsonb,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS execution_orders_event_idx
    ON autotrade_analytics.execution_orders(event_id);

CREATE TABLE IF NOT EXISTS autotrade_analytics.execution_results (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_order_id bigint NOT NULL REFERENCES autotrade_analytics.execution_orders(id),
    close_order_id    varchar(64),
    closed_qty        numeric,
    close_price       numeric,
    exit_reason       varchar(32),
    raw_response      jsonb,
    recorded_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS autotrade_analytics.execution_finances (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_order_id bigint NOT NULL REFERENCES autotrade_analytics.execution_orders(id),
    fee               numeric,
    funding           numeric,
    realized_pnl      numeric,
    raw_response      jsonb,
    recorded_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS autotrade_analytics.control_logs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamptz NOT NULL DEFAULT now(),
    layer        varchar(4)  NOT NULL CHECK (layer IN ('L1','L2','L3','L4','L5')),
    symbol       varchar(20),
    event_id     varchar(120),
    order_id     varchar(64),
    step         varchar(32),
    error_code   varchar(64),
    message      text        NOT NULL,
    details      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    discord_status varchar(16) NOT NULL DEFAULT 'pending'
        CHECK (discord_status IN ('pending','sent','failed','skipped'))
);
CREATE INDEX IF NOT EXISTS control_logs_created_idx
    ON autotrade_analytics.control_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS control_logs_event_idx
    ON autotrade_analytics.control_logs(event_id);

COMMIT;
